const DEFAULT_LANGUAGE_MESSAGES: AppMessagesMap = messages[Language.English]!;

export function getLocalizedAppMessage(
  key: AppMessageKey,
  language: Language = Language.English,
): string {
  const langMessages: AppMessagesMap = messages[language] ?? DEFAULT_LANGUAGE_MESSAGES;
  return langMessages[key] ?? key;
}

export function hasAppMessage(key: AppMessageKey, language: Language = Language.English): boolean {
  const langMessages: AppMessagesMap = messages[language] ?? DEFAULT_LANGUAGE_MESSAGES;
  return key in langMessages;
}
